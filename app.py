# ------------------------- 计分逻辑 -------------------------
def compute_result(answers):
    """answers: {题目key: 所选选项序号}。返回 (四字母类型代码, 各维度明细列表)。

    计分方式：每题所选选项的计分方向字母 +1；每维度得票多的一端胜出。
    仅 2 题的维度若出现平局，按 TIE_BREAK 固定规则归入，保证结果唯一。
    """
    scores = {dim: {p: 0 for p in DIMENSIONS[dim]} for dim in DIMENSION_ORDER}
    for q in QUESTIONS:
        # radio 在 session_state 中保存的是所选选项文案，据此查表得到计分方向
        selected = answers[q["key"]]
        pole = next(p for text, p in q["options"] if text == selected)
        scores[q["dim"]][pole] += 1

    code, details = "", []
    for dim in DIMENSION_ORDER:
        pole_a, pole_b = list(DIMENSIONS[dim].keys())  # 如 ["Q", "S"]
        sa, sb = scores[dim][pole_a], scores[dim][pole_b]
        tie = sa == sb
        if sa > sb:
            winner = pole_a
        elif sb > sa:
            winner = pole_b
        else:
            winner = TIE_BREAK[dim]  # 固定平局规则
        code += winner
        details.append({
            "a": pole_a, "b": pole_b, "sa": sa, "sb": sb,
            "tie": tie, "winner": winner,
            "a_name": DIMENSIONS[dim][pole_a][0],
            "b_name": DIMENSIONS[dim][pole_b][0],
            "winner_name": DIMENSIONS[dim][winner][0],
        })
    return code, details

