def render_form():
    st.subheader("✈️ 开始测试")
    st.caption(
        "计分说明：每题两个选项分别对应所在维度的一端，按所选数量计票；"
        "「经济/舒适」「城市/自然」两维度若两题各选一出现平局，按固定规则分别归入 "
        "B（经济实用）和 U（城市便利），保证结果唯一。"
    )
    with st.form("quiz_form"):
        for i, q in enumerate(QUESTIONS, start=1):
            labels = [opt[0] for opt in q["options"]]
            st.radio(f"**第 {i} 题｜{q['text']}**", options=labels,
                     index=None, key=q["key"])
        submitted = st.form_submit_button("提交并查看结果 🚀", use_container_width=True)

    if submitted:
        unanswered = [i for i, q in enumerate(QUESTIONS, start=1)
                      if st.session_state.get(q["key"]) is None]
        if unanswered:
            st.error(
                f"还有 **{len(unanswered)}** 道题未作答（第 "
                f"{'、'.join(map(str, unanswered))} 题），请全部作答后再提交。"
            )
        else:
            answers = {q["key"]: st.session_state[q["key"]] for q in QUESTIONS}
            code, details = compute_result(answers)
            st.session_state["result"] = {"code": code, "details": details}
            st.rerun()

